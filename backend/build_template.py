def build_xlsx(path):
    wb=Workbook(); thin=Side(style="thin",color="D9C6A6")
    hfill=PatternFill("solid",fgColor="0B6E6E"); hfont=Font(bold=True,color="FFFFFF",size=12)
    def sheet(ws,head,rows,widths):
        ws.append(head)
        for r in rows: ws.append(r)
        for i,c in enumerate(ws[1],1):
            c.fill=hfill; c.font=hfont; c.alignment=Alignment(vertical="center",wrap_text=True)
        for row in ws.iter_rows(min_row=2):
            for c in row: c.alignment=Alignment(vertical="top",wrap_text=True); c.border=Border(bottom=thin)
        for i,w in enumerate(widths): ws.column_dimensions[chr(65+i)].width=w
        ws.freeze_panes="A2"; ws.row_dimensions[1].height=34
    ws=wb.active; ws.title="使用說明"
    for line in HELP: ws.append([line])
    ws.column_dimensions["A"].width=110; ws["A1"].font=Font(bold=True,size=14,color="0B6E6E")
    for r in ws.iter_rows():
        for c in r:
            c.alignment=Alignment(wrap_text=True,vertical="top")
            if c.value and str(c.value)[:1] in "一二三四五": c.font=Font(bold=True,size=12)
    ws=wb.create_sheet("物件"); sheet(ws,L_HEAD,[r+[""] for r in L],[8,9,10,11,28,14,14,14,8,11,13,9,8,22,36,30,8,6,16,16])
    for col,opts in (("B",'"是,否"'),("C",'"買賣,出租"'),("D",'"一房,兩房,三房,四房以上,店面・辦公,廠房,土地"'),("Q",'"是,否"')):
        dv=DataValidation(type="list",formula1=opts,allow_blank=True); dv.add(f"{col}2:{col}500"); ws.add_data_validation(dv)
    ws=wb.create_sheet("網站文字"); sheet(ws,C_HEAD,C,[18,34,90])
    ws=wb.create_sheet("客戶留言"); sheet(ws,LEAD_HEAD,[],[18,10,14,14,10,14,14,50,8,10,20])
    dv=DataValidation(type="list",formula1='"新留言,已聯絡,處理中,已結案"',allow_blank=True); dv.add("J2:J2000"); ws.add_data_validation(dv)
    wb.save(path)

def write_csv(path,head,rows):
    with open(path,"w",encoding="utf-8",newline="") as f:
        w=csv.writer(f); w.writerow(head); [w.writerow(r) for r in rows]

